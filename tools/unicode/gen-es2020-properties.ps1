<#
.SYNOPSIS
    Writes src/Corvus.Ecma262.RegularExpressions.Es2020.pas, the Unicode property names and values of the tables of
    ECMAScript 2020.

.DESCRIPTION
    The grammar of ECMAScript 2020 knows only the property names and values of its own tables, whatever the version of
    Unicode. This script copies them from es2020.rs of the corvus-regex-ecma262 Rust crate, so every engine's 2020
    grammar knows the same names. Pascal has no case statement over strings that Delphi also compiles, so each list is
    written in ordinal order, and the unit searches it.

.PARAMETER CrateEs2020
    The path of corvus-regex-ecma262/src/es2020.rs in a checkout of the Rust crate.

.PARAMETER Output
    The file to write. The default is src/Corvus.Ecma262.RegularExpressions.Es2020.pas of this repository.

.PARAMETER Check
    Compares what would be written with the file in place and writes nothing. The script fails when they differ.
#>
param(
    [Parameter(Mandatory = $true)][string]$CrateEs2020,
    [string]$Output = (Join-Path (Join-Path (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent) 'src') 'Corvus.Ecma262.RegularExpressions.Es2020.pas'),
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$source = [System.IO.File]::ReadAllText((Resolve-Path $CrateEs2020))

function Get-Names([string]$rustFn) {
    $m = [regex]::Match($source, "fn $rustFn\(name: &str\) -> bool \{\s*matches!\(\s*name,(.*?)\)\s*\}", 'Singleline')
    if (-not $m.Success) { throw "es2020.rs has no $rustFn. The generator needs updating for the crate's file." }
    $names = [System.Collections.Generic.List[string]]::new()
    foreach ($n in [regex]::Matches($m.Groups[1].Value, '"([^"]*)"')) { $names.Add($n.Groups[1].Value) }
    if ($names.Count -eq 0) { throw "es2020.rs lists no names in $rustFn." }
    $names.Sort([System.StringComparer]::Ordinal)
    return , $names.ToArray()
}

$out = [System.Text.StringBuilder]::new()
function Add-Line([string]$line = '') { [void]$out.Append($line).Append("`n") }

# Writes items separated by commas, in rows no longer than a line of the package may be.
function Add-Wrapped([string]$indent, [string[]]$items) {
    $row = [System.Text.StringBuilder]::new($indent)
    for ($k = 0; $k -lt $items.Count; $k++) {
        $item = $items[$k]
        if ($k -lt $items.Count - 1) { $item += ',' }
        if ($row.Length -gt $indent.Length -and $row.Length + 1 + $item.Length -gt 118) {
            Add-Line $row.ToString()
            $row = [System.Text.StringBuilder]::new($indent)
        }
        if ($row.Length -gt $indent.Length) { [void]$row.Append(' ') }
        [void]$row.Append($item)
    }
    if ($row.Length -gt $indent.Length) { Add-Line $row.ToString() }
}

$lists = @(
    @{ Name = 'NonBinary'; Doc = 'The non-binary properties.'; Values = (Get-Names 'non_binary') },
    @{ Name = 'Binary'; Doc = 'The binary properties.'; Values = (Get-Names 'binary') },
    @{ Name = 'Category'; Doc = 'The General_Category values.'; Values = (Get-Names 'category') },
    @{ Name = 'Script'; Doc = 'The Script values.'; Values = (Get-Names 'script') }
)

Add-Line 'unit Corvus.Ecma262.RegularExpressions.Es2020;'
Add-Line '{$I ecma262.inc}'
Add-Line
Add-Line '{ Code generated by tools/unicode/gen-es2020-properties.ps1 from es2020.rs of the corvus-regex-ecma262 Rust crate.'
Add-Line '  DO NOT EDIT.'
Add-Line
Add-Line '  The Unicode property names and values of the tables of ECMAScript 2020 (ECMA-262, 11th edition), the only ones'
Add-Line '  its grammar knows whatever the version of Unicode: tc39/ecma262 at the tag es2020, every name and alias of each. }'
Add-Line
Add-Line 'interface'
Add-Line
Add-Line '(* Es2020HasProperty reports whether the expression between the braces of \p{...} names a property, and a value of'
Add-Line '  it, of the tables: a name and a value joined by =, or the lone name of a General_Category value or of a binary'
Add-Line '  property. *)'
Add-Line 'function Es2020HasProperty(const Expr: UTF8String): Boolean;'
Add-Line
Add-Line 'implementation'
Add-Line
Add-Line 'const'
foreach ($list in $lists) {
    Add-Line "  { $($list.Doc) }"
    Add-Line "  $($list.Name)Names: array[0..$($list.Values.Count - 1)] of UTF8String = ("
    Add-Wrapped '    ' @($list.Values | ForEach-Object { "'$_'" })
    Add-Line '  );'
    Add-Line
}
Add-Line '{ Holds searches names in ordinal order for a name. }'
Add-Line 'function Holds(const Names: array of UTF8String; const Name: UTF8String): Boolean;'
Add-Line 'var'
Add-Line '  Lo, Hi, Mid: Int32;'
Add-Line 'begin'
Add-Line '  Lo := 0;'
Add-Line '  Hi := Length(Names);'
Add-Line '  while Lo < Hi do begin'
Add-Line '    Mid := (Lo + Hi) shr 1;'
Add-Line '    if Names[Mid] < Name then'
Add-Line '      Lo := Mid + 1'
Add-Line '    else if Names[Mid] > Name then'
Add-Line '      Hi := Mid'
Add-Line '    else'
Add-Line '      Exit(True);'
Add-Line '  end;'
Add-Line '  Result := False;'
Add-Line 'end;'
Add-Line
Add-Line 'function Es2020HasProperty(const Expr: UTF8String): Boolean;'
Add-Line 'var'
Add-Line '  I: Int32;'
Add-Line '  Name, Value: UTF8String;'
Add-Line 'begin'
Add-Line '  I := Pos(''='', Expr);'
Add-Line '  if I = 0 then'
Add-Line '    Exit(Holds(CategoryNames, Expr) or Holds(BinaryNames, Expr));'
Add-Line '  Name := Copy(Expr, 1, I - 1);'
Add-Line '  Value := Copy(Expr, I + 1, Length(Expr) - I);'
Add-Line '  if (Name = ''General_Category'') or (Name = ''gc'') then'
Add-Line '    Exit(Holds(CategoryNames, Value));'
Add-Line '  Result := Holds(NonBinaryNames, Name) and Holds(ScriptNames, Value);'
Add-Line 'end;'
Add-Line
Add-Line 'end.'

$text = $out.ToString().TrimEnd("`n")
foreach ($line in $text -split "`n") {
    if ($line.Length -gt 120) { throw "A line of the output is longer than 120 characters: $line" }
}
$count = ($lists | ForEach-Object { $_.Values.Count } | Measure-Object -Sum).Sum
if ($Check) {
    $current = if (Test-Path $Output) { [System.IO.File]::ReadAllText($Output) } else { '' }
    if ($current -ne $text) { throw "$Output is not what $CrateEs2020 generates. Run tools/unicode/gen-es2020-properties.ps1." }
    Write-Host "$Output is current ($count names)."
    return
}
# The file ends without a line break, as every file of the package does.
[System.IO.File]::WriteAllText($Output, $text, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $Output with $count names."
