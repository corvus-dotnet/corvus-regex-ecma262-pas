<#
.SYNOPSIS
    Writes src/Corvus.Ecma262.RegularExpressions.StringsTables.inc, the properties of strings of the engine.

.DESCRIPTION
    The properties of strings (RGI_Emoji and the six it is the union of) are what only the v flag can name. This
    script copies them from strings_gen.rs of the corvus-regex-ecma262 Rust crate, so every engine holds the same
    Unicode emoji sequences. Each property is its name, its single code points as hexadecimal ranges, and its
    sequences as hexadecimal code points, a space between the code points of a sequence and a semicolon between
    sequences. A long string is written as a sum of pieces, each on a line of its own.

.PARAMETER CrateStrings
    The path of corvus-regex-ecma262/src/strings_gen.rs in a checkout of the Rust crate.

.PARAMETER Output
    The file to write. The default is src/Corvus.Ecma262.RegularExpressions.StringsTables.inc of this repository.

.PARAMETER Check
    Compares what would be written with the file in place and writes nothing. The script fails when they differ.
#>
param(
    [Parameter(Mandatory = $true)][string]$CrateStrings,
    [string]$Output = (Join-Path (Join-Path (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent) 'src') 'Corvus.Ecma262.RegularExpressions.StringsTables.inc'),
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$source = [System.IO.File]::ReadAllText((Resolve-Path $CrateStrings))
$version = [regex]::Match($source, 'pub\(crate\) const VERSION: &str = "([^"]+)";').Groups[1].Value
$body = [regex]::Match($source, 'pub\(crate\) static PROPERTIES: \[\(&str, &str, &str\); \d+\] = \[(.*?)\n\];', 'Singleline')
if (-not $version -or -not $body.Success) { throw "strings_gen.rs has changed shape. The generator needs updating for the crate's file." }
$rows = @([regex]::Matches($body.Groups[1].Value, '\("([^"]*)", "([^"]*)", "([^"]*)"\),'))
if ($rows.Count -eq 0) { throw 'strings_gen.rs has no rows in PROPERTIES.' }

$out = [System.Text.StringBuilder]::new()
function Add-Line([string]$line = '') { [void]$out.Append($line).Append("`n") }

# Writes a string constant as pieces of at most 100 characters, cut at a space or a semicolon where there is one.
function Add-Pieces([string]$indent, [string]$value, [string]$end) {
    if ($value.Length -eq 0) { Add-Line "$indent''$end"; return }
    $pieces = [System.Collections.Generic.List[string]]::new()
    $at = 0
    while ($at -lt $value.Length) {
        $n = [Math]::Min(100, $value.Length - $at)
        if ($at + $n -lt $value.Length) {
            $cut = $value.LastIndexOfAny([char[]]@(' ', ';'), $at + $n - 1, $n)
            if ($cut -gt $at) { $n = $cut - $at + 1 }
        }
        $pieces.Add($value.Substring($at, $n))
        $at += $n
    }
    for ($k = 0; $k -lt $pieces.Count; $k++) {
        $tail = if ($k -eq $pieces.Count - 1) { $end } else { ' +' }
        Add-Line "$indent'$($pieces[$k])'$tail"
    }
}

Add-Line '{ Code generated by tools/unicode/gen-strings.ps1 from strings_gen.rs of the corvus-regex-ecma262 Rust crate'
Add-Line "  (emoji-sequences.txt and emoji-zwj-sequences.txt of Unicode $version). DO NOT EDIT. }"
Add-Line
Add-Line 'const'
Add-Line '  { StringsVersion is the version of Unicode the properties of strings are from. }'
Add-Line "  StringsVersion = '$version';"
Add-Line
Add-Line '  { StringPropertyCount is the number of properties of strings but RGI_Emoji (the union of them all). Each has its'
Add-Line '    name, its single code points as hexadecimal ranges, and its sequences as hexadecimal code points, a space'
Add-Line '    between the code points of a sequence and a semicolon between sequences. }'
Add-Line "  StringPropertyCount = $($rows.Count);"
Add-Line "  StringPropertyNames: array[0..$($rows.Count - 1)] of UTF8String = ("
for ($k = 0; $k -lt $rows.Count; $k++) {
    Add-Line ("    '$($rows[$k].Groups[1].Value)'" + $(if ($k -eq $rows.Count - 1) { '' } else { ',' }))
}
Add-Line '  );'
Add-Line "  StringPropertyPoints: array[0..$($rows.Count - 1)] of UTF8String = ("
for ($k = 0; $k -lt $rows.Count; $k++) {
    Add-Pieces '    ' $rows[$k].Groups[2].Value $(if ($k -eq $rows.Count - 1) { '' } else { ',' })
}
Add-Line '  );'
Add-Line "  StringPropertySequences: array[0..$($rows.Count - 1)] of UTF8String = ("
for ($k = 0; $k -lt $rows.Count; $k++) {
    Add-Pieces '    ' $rows[$k].Groups[3].Value $(if ($k -eq $rows.Count - 1) { '' } else { ',' })
}
Add-Line '  );'

$text = $out.ToString().TrimEnd("`n")
foreach ($line in $text -split "`n") {
    if ($line.Length -gt 120) { throw "A line of the output is longer than 120 characters: $line" }
}
if ($Check) {
    $current = if (Test-Path $Output) { [System.IO.File]::ReadAllText($Output) } else { '' }
    if ($current -ne $text) { throw "$Output is not what $CrateStrings generates. Run tools/unicode/gen-strings.ps1." }
    Write-Host "$Output is current ($($rows.Count) properties)."
    return
}
[System.IO.File]::WriteAllText($Output, $text, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $Output with $($rows.Count) properties of strings, Unicode $version."
